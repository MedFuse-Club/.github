let slideIndex = 1;
showSlides(slideIndex);

function plusSlides(n) {
    showSlides(slideIndex += n);
}

function showSlides(n) {
    let i;
    let slides = document.getElementsByClassName("carousel-slide");
    if (n > slides.length) {slideIndex = 1}
    if (n < 1) {slideIndex = slides.length}
    for (i = 0; i < slides.length; i++) {
        slides[i].className = slides[i].className.replace(" active", "");
        slides[i].style.display = "none";
    }
    slides[slideIndex-1].style.display = "block";
    slides[slideIndex-1].className += " active";
}

// Expose functions to the global window object for HTML onclick attributes
window.plusSlides = plusSlides;

function toggleShare() {
    const menu = document.getElementById("share-menu");
    menu.classList.toggle("show");
}

// Close the share menu if clicked outside
window.addEventListener('click', function(event) {
    if (!event.target.matches('.share-button')) {
        const dropdowns = document.getElementsByClassName("share-menu");
        for (let i = 0; i < dropdowns.length; i++) {
            let openDropdown = dropdowns[i];
            if (openDropdown.classList.contains('show')) {
                openDropdown.classList.remove('show');
            }
        }
    }
});
